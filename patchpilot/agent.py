"""The controller owns validation and publication eligibility, never the model."""
from dataclasses import asdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import time
import uuid

from .providers import Budget, BudgetExceeded
from .report import render
from .runtime import git, snapshot
from .tools import Toolset


def run(source: Path, issue: str, provider, output: Path, runner="local", budget=None) -> dict:
    budget = budget or Budget()
    run_id = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + uuid.uuid4().hex[:8]
    folder = output.resolve() / run_id
    folder.mkdir(parents=True)
    workspace = folder / "workspace"
    started = time.monotonic()
    base = snapshot(source, workspace)
    tools = Toolset(workspace, runner)
    events = []
    status, error = "failed", None
    previous = None
    try:
        # Always establish baseline evidence before the provider acts.
        budget.step()
        previous_baseline = tools.call("run_tests", {})
        event = {"step": budget.steps, "tool": "run_tests", "arguments": {}, "result": previous_baseline}
        events.append(event)
        with (folder / "trace.jsonl").open("a") as stream:
            stream.write(json.dumps(event) + "\n")
        while True:
            if budget.steps >= budget.max_steps:
                raise BudgetExceeded("Tool step budget exhausted")
            action = provider.next(previous, budget)
            if action is None:
                error = "Provider stopped before producing a validated patch"
                break
            budget.step()
            previous = tools.call(action["name"], action["arguments"])
            event = {"step": budget.steps, "tool": action["name"], "arguments": action["arguments"],
                     "result": previous, "elapsed_seconds": round(time.monotonic() - started, 3)}
            events.append(event)
            with (folder / "trace.jsonl").open("a") as stream:
                stream.write(json.dumps(event) + "\n")
            if action["name"] == "finish" and previous.get("ok"):
                status = "awaiting_review"
                break
    except BudgetExceeded as exc:
        status, error = "budget_exhausted", str(exc)
    except Exception as exc:
        status, error = "failed", f"{type(exc).__name__}: {exc}"
    patch = git(workspace, "diff", "--no-ext-diff", "--no-textconv")
    if patch:
        patch += "\n"
    (folder / "patch.diff").write_text(patch)
    result = {"run_id": run_id, "status": status, "provider": provider.name,
              "model": getattr(provider, "model", None), "issue": issue,
              "source": str(source.resolve()), "base_commit": base,
              "workspace": str(workspace), "artifacts": str(folder),
              "plan": tools.plan, "summary": tools.summary, "error": error,
              "patch_sha256": hashlib.sha256(patch.encode()).hexdigest(),
              "validated_tree": tools.validated_tree, "test_runs": tools.tests,
              "budget": asdict(budget), "provider_retries": getattr(provider, "retries", 0),
              "duration_seconds": round(time.monotonic() - started, 3)}
    (folder / "run.json").write_text(json.dumps(result, indent=2) + "\n")
    (folder / "pr.md").write_text(f"{tools.summary or 'Incomplete maintenance run'}\n\n"
                                  f"{tools.plan}\n\nGenerated by PatchPilot using {provider.name}. "
                                  f"Review the patch and test evidence before merging.\n")
    render(folder, result, events, patch)
    return result
